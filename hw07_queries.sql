-- =====================================================================
-- Завдання 1.
-- Скриншот: p1_year_month_day.png
-- =====================================================================
USE mydb;

SELECT id, date,
       YEAR(date)  AS year,
       MONTH(date) AS month,
       DAY(date)   AS day
FROM orders;

-- =====================================================================
-- Завдання 2.
-- Скриншот: p2_date_add_one_day.png
-- =====================================================================
SELECT id, date,
       DATE_ADD(date, INTERVAL 1 DAY) AS date_plus_one_day
FROM orders;

-- =====================================================================
-- Завдання 3.
-- Скриншот: p3_unix_timestamp.png
-- =====================================================================
SELECT id, date,
       UNIX_TIMESTAMP(CAST(date AS DATE)) AS unix_timestamp
FROM orders;

-- =====================================================================
-- Завдання 4.
-- Скриншот: p4_count_between_dates.png
-- =====================================================================
SELECT COUNT(*) AS orders_count
  FROM orders
WHERE CAST(date AS DATETIME) BETWEEN '1996-07-10 00:00:00' AND '1996-10-08 00:00:00';

-- =====================================================================
-- Завдання 5.
-- Скриншот: p5_json_object.png
-- =====================================================================
SELECT id, date,
       JSON_OBJECT('id', id, 'date', date) AS json_data
FROM orders;
